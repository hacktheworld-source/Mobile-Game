// --- authoring guard: fail loudly at load if any screen is malformed ---
for (const [id, s] of Object.entries(SCREENS)) {
  if (s.tiles.length !== GRID_H) {
    throw new Error(`Screen ${id} (${s.name}): ${s.tiles.length} rows, expected ${GRID_H}`);
  }
  s.tiles.forEach((row, y) => {
    if (row.length !== GRID_W) {
      throw new Error(`Screen ${id} (${s.name}) row ${y}: ${row.length} chars, expected ${GRID_W}`);
    }
  });
}
